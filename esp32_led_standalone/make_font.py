from PIL import Image,ImageDraw,ImageFont
from pathlib import Path
chars=''.join(chr(i) for i in range(32,127))+'ĄĆĘŁŃÓŚŹŻąćęłńóśźż'
font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',9)
out=['// Generated by make_font.py: 10-pixel font with Polish glyphs.',
     'struct Glyph { uint32_t code; uint8_t width; uint16_t rows[10]; };',
     'static const Glyph glyphs[] = {']
for ch in chars:
    im=Image.new('L',(12,10));ImageDraw.Draw(im).text((0,-1),ch,font=font,fill=255)
    w=min(12,max(2,int(font.getlength(ch)+.5)))
    rows=[sum((1<<x) for x in range(w) if im.getpixel((x,y))>=90) for y in range(10)]
    out.append('{%d,%d,{%s}},'%(ord(ch),w,','.join(map(str,rows))))
out.append('};')
Path(__file__).with_name('font.h').write_text('\n'.join(out)+'\n')
